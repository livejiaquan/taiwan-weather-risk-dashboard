/**
 * Generates src/lib/countyShapes.ts from the taiwan-atlas county TopoJSON.
 *
 * Source: taiwan-atlas 2021.9.20 (MIT, Daniel Kao), derived from the Ministry
 * of the Interior "直轄市、縣市界線(TWD97經緯度)" open dataset. The mercator
 * variant already places Kinmen, Matsu and Penghu in insets.
 *
 * Run: npx tsx scripts/build-county-map.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoIdentity, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";
import { presimplify, quantile, simplify } from "topojson-simplify";
import type { Feature, FeatureCollection, Geometry } from "geojson";
import type { Topology } from "topojson-specification";
import { COUNTIES } from "../src/lib/riskEngine";

const WIDTH = 360;
const HEIGHT = 520;
// topojson-simplify quantile(p) keeps roughly the top p share of points by weight.
const KEEP_RATIO = 0.08;
// Islets smaller than this (in viewBox px²) are dropped unless they are the
// county's largest polygon, keeping the bundle small without losing a county.
const MIN_POLYGON_AREA = 1.5;

const raw = JSON.parse(readFileSync("scripts/data/counties-mercator-10t.json", "utf8")) as Topology<any>;
const pre = presimplify(raw);
const topology = simplify(pre, quantile(pre, KEEP_RATIO));

const counties = feature(topology, topology.objects.counties) as unknown as FeatureCollection<
  Geometry,
  { COUNTYNAME: string; COUNTYENG: string }
>;
const insetMesh = mesh(topology, topology.objects.compBorders as never);
const projection = geoIdentity().fitExtent(
  [
    [4, 4],
    [WIDTH - 4, HEIGHT - 4],
  ],
  { type: "FeatureCollection", features: [...counties.features, { type: "Feature", properties: {}, geometry: insetMesh } as Feature] },
);
const path = geoPath(projection).digits(1);

for (const county of counties.features) {
  if (county.geometry.type !== "MultiPolygon") continue;
  const polygons = county.geometry.coordinates;
  const areas = polygons.map((coordinates) => path.area({ type: "Polygon", coordinates }));
  const largest = Math.max(...areas);
  county.geometry.coordinates = polygons.filter((_, index) => areas[index] >= MIN_POLYGON_AREA || areas[index] === largest);
}

const knownNames = new Set(COUNTIES.map((county) => county.countyName));
const shapes = counties.features.map((county) => {
  const countyName = county.properties.COUNTYNAME.replace(/^台/, "臺");
  if (!knownNames.has(countyName)) throw new Error(`Unknown county in atlas: ${countyName}`);
  const [cx, cy] = path.centroid(county);
  const [[x0, y0], [x1, y1]] = path.bounds(county);
  const bounds = [x0, y0, x1, y1].map((value) => Math.round(value)) as [number, number, number, number];
  return { countyName, d: path(county) ?? "", cx: Math.round(cx), cy: Math.round(cy), bounds };
});
if (shapes.length !== COUNTIES.length) throw new Error(`Expected ${COUNTIES.length} counties, got ${shapes.length}`);

const insetBorders = path(insetMesh) ?? "";

shapes.sort(
  (a, b) =>
    COUNTIES.findIndex((county) => county.countyName === a.countyName) -
    COUNTIES.findIndex((county) => county.countyName === b.countyName),
);

const output = `// Generated by scripts/build-county-map.ts — do not edit by hand.
// Geometry: taiwan-atlas (MIT) derived from MOI open data 直轄市、縣市界線.

export interface CountyShape {
  countyName: string;
  d: string;
  cx: number;
  cy: number;
  /** [x0, y0, x1, y1] in viewBox units; used for tap targets on small islands. */
  bounds: [number, number, number, number];
}

export const COUNTY_MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export const COUNTY_INSET_BORDERS = ${JSON.stringify(insetBorders)};

export const COUNTY_SHAPES: CountyShape[] = ${JSON.stringify(shapes)};
`;

writeFileSync("src/lib/countyShapes.ts", output);
console.log(`Wrote ${shapes.length} county shapes (${Math.round(output.length / 1024)} KiB).`);
